// dsh-bridge 设置面板 / 移动端弹窗的中英文词典（渲染层兜底翻译用）。
//
// 设计（与 locales.mjs 的语义化键词典并存，两者分工不同）：
//   - locales.mjs 的 `zh` / `en` 是**语义化键**（如 'menu.open'），用于 DOM 注入、
//     innerHTML、aria/title 属性等「拿不到原文上下文」的调用点；
//   - 本文件的 `panelEn` 是**中文原文 → 英文译文**的映射（gettext 风格），用于
//     React 渲染层：client/index.js 的 `h()` 包装器在渲染时把字符串子节点 / title /
//     placeholder / aria-label / alt 交给 localeT()，精确命中词典才替换，未命中
//     原样返回（用户数据、路径、代码、日志绝不会被误翻）。
//
// 约定：
//   - 键必须是源码里**原样**出现的字符串（含 emoji 与标点），由
//     test/panel-i18n.test.mjs 强制：源码新出现的中文文案若不在词典里就测试失败；
//   - 动态拼接的键用 `${name}` 占位符，调用 `localeT('…${name}…', { name })`；
//   - 值为数组时表示英文单复数 `[单数, 复数]`，按 `vars.count` 选择（中文无此需求）。
//
// 中文模式下 localeT() 直接返回原文（键本身），所以这里只需维护英文。
// 维护方式见 test/panel-i18n.test.mjs 的失败提示（新增中文文案必须补词条）。

